package towerdefence.ui.input;

import towerdefence.game.Game;
import towerdefence.game.input.InputCommand;
import towerdefence.game.interfaces.InputSource;
import towerdefence.system.config.Config;
import towerdefence.util.Vector2D;

import javax.swing.*;
import java.awt.*;
import java.awt.event.MouseAdapter;
import java.awt.event.MouseEvent;
import java.util.ArrayList;
import java.util.List;
import java.util.Queue;
import java.util.concurrent.ConcurrentLinkedQueue;


public class SwingInputSource implements InputSource {
    private final Game game;
    private final Config config;
    private final InputMapping inputMapping;
    private final JComponent component;

    private final Queue<InputCommand> inputQueue = new ConcurrentLinkedQueue<>();

    /**
     * Creates a new SwingInputSource with the given game, config, input mapping, and component. The input source will listen for mouse clicks on the component and translate them into game commands based on the input mapping and game state.
     *
     * @param game         the Game instance to which this input source will send commands based on user input
     * @param config       the Config instance containing game configuration values such as game width and tower spot radius, which may be used for translating input coordinates to game commands
     * @param inputMapping the InputMapping instance responsible for translating screen coordinates to world coordinates, allowing the input source to determine which game entities (e.g., tower spots) are being interacted with based on mouse clicks
     * @param component    the JComponent to which this input source will attach mouse listeners for detecting user input; typically this would be the main game view component where the user interacts with the game
     */
    public SwingInputSource(Game game, Config config, InputMapping inputMapping, JComponent component) {
        this.game = game;
        this.config = config;
        this.inputMapping = inputMapping;
        this.component = component;
    }

    /**
     * Polls the input queue for any pending input commands and returns them as a list. This method is called by the game loop to retrieve user input commands that have been generated based on mouse interactions with the game view. The input commands are generated by the mouse listener attached to the component, which translates mouse clicks into game commands such as opening or closing the build menu based on the location of the click and the presence of tower spots.
     *
     * @return a list of InputCommand instances representing user input commands that have been generated since the last poll; this list may be empty if no new input commands have been generated
     */
    @Override
    public List<InputCommand> pollCommands() {
        List<InputCommand> commands = new ArrayList<>();
        InputCommand command;
        while ((command = inputQueue.poll()) != null) {
            commands.add(command);
        }
        return commands;
    }

    /**
     * Translates a screen coordinate point from a mouse click into the index of a tower spot in the game, if the click is within the radius of a tower spot. This method uses the input mapping to convert the screen coordinates to world coordinates, and then checks the distance from the click to each tower spot to determine if it is close enough to be considered a click on that spot. If a valid tower spot is found, its index is returned; otherwise, null is returned to indicate that no tower spot was clicked.
     *
     * @param p the Point representing the screen coordinates of a mouse click, which will be translated into world coordinates and checked against the locations of tower spots in the game to determine if a build menu should be opened for that spot
     * @return the index of the tower spot that was clicked on, if the click is within the radius of a tower spot; otherwise, null if no valid tower spot was clicked
     */
    private Integer findTowerSpotIndexFromPoint(Point p) {
        Vector2D pScaled = inputMapping.screenToWorld(p);
        if (pScaled == null) return null;

        List<Vector2D> spots = game.getTowerSpots();

        int best = -1;
        double bestD = config.getGameWidth() * 2;

        for (int i = 0; i < spots.size(); i++) {
            double d = pScaled.distanceTo(spots.get(i));
            if (d <= config.getTowerSpotRadius() && d < bestD) {
                bestD = d;
                best = i;
            }
        }

        if (best >= 0) {
            return best;
        } else {
            return null;
        }
    }

    /**
     * Installs mouse listeners on the component to detect user input and translate it into game commands. When the user clicks on the component, the mouse listener checks if the click is a left mouse button click and then uses the findTowerSpotIndexFromPoint method to determine if the click was on a tower spot. If a valid tower spot index is found, an InputCommand to open the build menu for that spot is added to the input queue; otherwise, an InputCommand to close the build menu is added to the input queue. This allows the game to respond to user interactions with the game view by opening or closing the build menu based on where the user clicks.
     */
    public void installHandlers() {
        component.setFocusable(true);
        component.setFocusTraversalKeysEnabled(false);
        component.addMouseListener(new MouseAdapter() {
            @Override
            public void mousePressed(MouseEvent e) {
                if (!SwingUtilities.isLeftMouseButton(e)) {
                    return;
                }
                Integer spotIndex = findTowerSpotIndexFromPoint(e.getPoint());
                if (spotIndex != null) {
                    inputQueue.add(InputCommand.openBuildMenu(spotIndex));
                } else {
                    inputQueue.add(InputCommand.closeBuildMenu());
                }
            }
        });
        SwingUtilities.invokeLater(component::requestFocusInWindow);
    }

    /**
     * Adds the given InputCommand to the input queue, which will be retrieved by the game loop when it polls for commands. This method is called by the mouse listener when a user interaction is detected, and it translates that interaction into a game command that can be processed by the game logic. For example, when a user clicks on a tower spot, an InputCommand to open the build menu for that spot is created and added to the input queue using this method.
     *
     * @param command the InputCommand to be added to the input queue, representing a user interaction that has been translated into a game command (e.g., opening the build menu for a tower spot); this command will be retrieved by the game loop when it polls for commands and processed accordingly
     */
    public void queueCommand(InputCommand command) {
        inputQueue.add(command);
    }
}
