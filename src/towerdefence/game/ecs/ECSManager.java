package towerdefence.game.ecs;

import towerdefence.game.ecs.components.spawn.SpawnCountComponent;
import towerdefence.game.ecs.components.spawn.SpawnPathComponent;
import towerdefence.game.ecs.components.spawn.SpawnScheduleComponent;
import towerdefence.game.ecs.components.spawn.SpawnTypeComponent;

import java.util.HashMap;
import java.util.HashSet;
import java.util.Map;
import java.util.Set;

public class ECSManager {
    private final Set<Integer> ECSentities = new HashSet<>();
    private final Map<Integer, SpawnScheduleComponent> spawnSchedules = new HashMap<>();
    private final Map<Integer, SpawnCountComponent> spawnCounts = new HashMap<>();
    private final Map<Integer, SpawnPathComponent> spawnPaths = new HashMap<>();
    private final Map<Integer, SpawnTypeComponent> spawnTypes = new HashMap<>();
    private int nextEntityId = 1;

    /**
     * Creates a new entity and returns its unique ID. The ID is generated by incrementing a counter, ensuring that each entity has a unique identifier.
     * The new entity is also added to the set of active entities.
     *
     * @return the unique ID of the newly created entity
     */
    public int createEntity() {
        int id = nextEntityId++;
        ECSentities.add(id);
        return id;
    }

    /**
     * Removes an entity and all of its associated components from the ECS.
     * This method takes the entity's unique ID as a parameter, removes it from the set of active entities, and also removes any components associated with that entity from their respective maps.
     *
     * @param id the unique ID of the entity to be removed
     */
    public void removeEntity(int id) {
        ECSentities.remove(id);
        spawnSchedules.remove(id);
        spawnCounts.remove(id);
        spawnPaths.remove(id);
        spawnTypes.remove(id);
    }

    /**
     * Gets a copy of the set of all active entity IDs in the ECS.
     *
     * @return an unmodifiable copy of the set of all active entity IDs in the ECS
     */
    public Set<Integer> getAllEntities() {
        return Set.copyOf(ECSentities);
    }

    /**
     * Gets a copy of the map of spawn schedules, where the keys are entity IDs and the values are SpawnScheduleComponent instances.
     *
     * @return an unmodifiable copy of the map of spawn schedules
     */
    public Map<Integer, SpawnScheduleComponent> getSpawnSchedules() {
        return Map.copyOf(spawnSchedules);
    }

    /**
     * Gets a copy of the map of spawn counts, where the keys are entity IDs and the values are SpawnCountComponent instances.
     *
     * @return an unmodifiable copy of the map of spawn counts
     */
    public Map<Integer, SpawnCountComponent> getSpawnCounts() {
        return Map.copyOf(spawnCounts);
    }

    /**
     * Gets a copy of the map of spawn paths, where the keys are entity IDs and the values are SpawnPathComponent instances.
     *
     * @return an unmodifiable copy of the map of spawn paths
     */
    public Map<Integer, SpawnPathComponent> getSpawnPaths() {
        return Map.copyOf(spawnPaths);
    }

    /**
     * Gets a copy of the map of spawn types, where the keys are entity IDs and the values are SpawnTypeComponent instances.
     *
     * @return an unmodifiable copy of the map of spawn types
     */
    public Map<Integer, SpawnTypeComponent> getSpawnTypes() {
        return Map.copyOf(spawnTypes);
    }

    /**
     * Adds a new spawn job to the ECS by associating the given components with the specified entity ID.
     *
     * @param id            the unique ID of the entity to which the spawn job components will be associated
     * @param spawnSchedule the SpawnScheduleComponent instance that defines the spawn schedule for the entity
     * @param spawnCount    the SpawnCountComponent instance that defines the spawn count for the entity
     * @param spawnPath     the SpawnPathComponent instance that defines the spawn path for the entity
     * @param spawnType     the SpawnTypeComponent instance that defines the spawn type for the entity
     */
    public void addSpawnJob(int id, SpawnScheduleComponent spawnSchedule, SpawnCountComponent spawnCount, SpawnPathComponent spawnPath, SpawnTypeComponent spawnType) {
        this.spawnSchedules.put(id, spawnSchedule);
        this.spawnCounts.put(id, spawnCount);
        this.spawnPaths.put(id, spawnPath);
        this.spawnTypes.put(id, spawnType);
    }
}
